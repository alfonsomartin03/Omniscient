def synth_room_points(rng: random.Random, count: int = 14000) -> list[tuple[float, float, float]]:
    x_max, y_max, z_max = ROOM
    rects = []  # (area, sampler)
    rects.append((x_max * y_max, lambda: (rng.uniform(0, x_max), rng.uniform(0, y_max), 0.0)))
    rects.append((x_max * y_max * 0.3, lambda: (rng.uniform(0, x_max), rng.uniform(0, y_max), z_max)))
    rects.append((y_max * z_max, lambda: (0.0, rng.uniform(0, y_max), rng.uniform(0, z_max))))
    rects.append((y_max * z_max, lambda: (x_max, rng.uniform(0, y_max), rng.uniform(0, z_max))))
    rects.append((x_max * z_max, lambda: (rng.uniform(0, x_max), 0.0, rng.uniform(0, z_max))))
    rects.append((x_max * z_max, lambda: (rng.uniform(0, x_max), y_max, rng.uniform(0, z_max))))

    def pillar():
        face = rng.randrange(4)
        a, b = rng.uniform(0, 0.5), rng.uniform(0, z_max)
        return [(7.75 + a, 5.75, b), (7.75 + a, 6.25, b), (7.75, 5.75 + a, b), (8.25, 5.75 + a, b)][face]

    def table():
        if rng.random() < 0.6:
            return (rng.uniform(2.2, 3.8), rng.uniform(3.6, 4.4), 0.75)
        face = rng.randrange(4)
        a, h = rng.uniform(0, 0.8), rng.uniform(0, 0.75)
        return [(2.2 + a * 2, 3.6, h), (2.2 + a * 2, 4.4, h), (2.2, 3.6 + a, h), (3.8, 3.6 + a, h)][face]

    rects.append((6.0, pillar))
    rects.append((5.0, table))
    total = sum(area for area, _ in rects)
    points = []
    for area, sample in rects:
        for _ in range(int(count * area / total)):
            x, y, z = sample()
            points.append((x + rng.gauss(0, 0.004), y + rng.gauss(0, 0.004), z + rng.gauss(0, 0.004)))
    return points


def write_ply(path: Path, points) -> None:
    lines = ["ply", "format ascii 1.0", "comment synthetic demo room (spatial.simulate); not a real scan",
             f"element vertex {len(points)}", "property float x", "property float y", "property float z", "end_header"]
    lines += [f"{x:.3f} {y:.3f} {z:.3f}" for x, y, z in points]
    path.write_text("\n".join(lines) + "\n")


def _as_tuple(spec):
    if isinstance(spec, dict):
        return (spec["start"], spec["end"], bool(spec.get("elevation", True)), [tuple(w) for w in spec["waypoints"]], spec["height"])
    return spec


def target_position(spec, t: float):
    start, end, _elevation, waypoints, height = _as_tuple(spec)
    if not start <= t <= end:
        return None
    speed = math.fsum(math.dist(a, b) for a, b in zip(waypoints, waypoints[1:])) / (end - start)
    travelled = (t - start) * speed
    for a, b in zip(waypoints, waypoints[1:]):
        length = math.dist(a, b)
        if travelled <= length:
            f = travelled / length if length else 0.0
            return (a[0] + (b[0] - a[0]) * f, a[1] + (b[1] - a[1]) * f, height)
        travelled -= length
    return (*waypoints[-1], height)


def simulate_radar(unit: SensorUnit, seed: int = 7, duration: float = DURATION_S, rate: float = RATE_HZ):
    """Return (header, frames, truth). Truth: {t: [(target_index, (x, y, z))]} for verification."""
    rng = random.Random(seed)
    radar = unit.radar
    header = {"format": FORMAT_ID, "sensor_id": radar.sensor_id, "frame": "radar", "units": dict(MEASUREMENT_UNITS),
              "rate_hz": rate, "duration_s": duration,
              "comment": "SIMULATED radar output. Azimuth is right-positive from boresight; elevation positive up."}
    frames, truth = [], {}
    steps = int(duration * rate)
    for step in range(steps):
        t = round(step / rate, 3)
        if DROPOUT[0] <= t < DROPOUT[1]:
            continue
        targets, truth[t] = [], []
        for index, spec in enumerate(TARGETS):
            position = target_position(spec, t)
            if position is None:
                continue
            truth[t].append((index, position))
            r, az, el = radar_point_from_map(position, unit)
            inside = (r <= radar.max_range_m and radar.azimuth_fov_deg[0] <= az <= radar.azimuth_fov_deg[1]
                      and radar.elevation_fov_deg[0] <= el <= radar.elevation_fov_deg[1])
            if not inside or rng.random() < 0.08:
                continue
            target = {"src_id": index + 1,
                      "range_m": round(r + rng.gauss(0, radar.sigma_range_m), 3),
                      "azimuth_deg": round(az + rng.gauss(0, radar.sigma_azimuth_deg), 2),
                      "snr_db": round(30 - 20 * math.log10(max(r, 1)) + rng.gauss(0, 1.5), 1)}
            if spec[2]:
                target["elevation_deg"] = round(el + rng.gauss(0, radar.sigma_elevation_deg), 2)
            targets.append(target)
        if rng.random() < 0.02:  # isolated clutter return
            targets.append({"range_m": round(rng.uniform(2, 12), 2), "azimuth_deg": round(rng.uniform(-50, 50), 1),
                            "snr_db": round(rng.uniform(4, 8), 1)})
        frames.append({"t": t, "targets": targets})
    return header, frames, truth


def build_demo_site(out: Path, seed: int = 7) -> None:
    out = Path(out)
    (out / "units").mkdir(parents=True, exist_ok=True)
    site, unit_doc = site_documents()
    (out / "site.json").write_text(json.dumps(site, indent=2) + "\n")
    (out / "units" / "unit-01.json").write_text(json.dumps(unit_doc, indent=2) + "\n")
    write_ply(out / "map.ply", synth_room_points(random.Random(seed)))
    unit = load_site(out).units["unit-01"]
    header, frames, _truth = simulate_radar(unit, seed)
    with (out / "radar_sample.jsonl").open("w") as handle:
        handle.write(json.dumps(header, separators=(",", ":")) + "\n")
        for frame in frames:
            handle.write(json.dumps(frame, separators=(",", ":")) + "\n")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("usage: python -m spatial.simulate <output-directory>")
    build_demo_site(Path(sys.argv[1]))
    print(f"Wrote simulated demo site to {sys.argv[1]}")


