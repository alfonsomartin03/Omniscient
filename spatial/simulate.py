SIM_LOOP_PADDING_S = 2.0


def _pose_doc(position, yaw, pitch, roll) -> dict:
    return {"translation_m": [round(v, 4) for v in position],
            "rotation": {"rpy_deg": {"yaw": round(yaw, 3), "pitch": round(pitch, 3), "roll": round(roll, 3)}}}


def scenario_for_bounds(lo, hi, floor_z: float, seed: int = 7) -> dict:
    """A simulated unit mounted on the low-y wall of the map, plus two anonymous walkers, scaled to the map.
    The true pose deliberately differs from any sensible first guess so calibration has something to find."""
    rng = random.Random(seed)
    width, depth = hi[0] - lo[0], hi[1] - lo[1]
    position = ((lo[0] + hi[0]) / 2 + rng.uniform(-0.3, 0.3), lo[1] + 0.25 + rng.uniform(-0.1, 0.1), floor_z + 2.4)
    mount = _pose_doc(position, rng.uniform(-5, 5), -rng.uniform(10, 14), 0.0)
    camera = _pose_doc((0.04, 0.03, 0.05), rng.choice((-1, 1)) * rng.uniform(1.2, 2.5), rng.choice((-1, 1)) * rng.uniform(0.6, 1.5),
                       rng.choice((-1, 1)) * rng.uniform(0.3, 0.8))

    def path(points):
        return [[round(lo[0] + fx * width, 3), round(lo[1] + fy * depth, 3)] for fx, fy in points]
    targets = [{"start": 2.0, "end": 50.0, "elevation": True, "height": floor_z + 1.0,
                "waypoints": path([(0.17, 0.83), (0.5, 0.45), (0.83, 0.83), (0.5, 0.67)])},
               {"start": 10.0, "end": 58.0, "elevation": False, "height": floor_z + 1.0,
                "waypoints": path([(0.875, 0.22), (0.25, 0.28), (0.25, 0.78)])}]
    intrinsics = {"model": "pinhole_brown_conrady", "width": 1280, "height": 720, "fx": 900, "fy": 900, "cx": 640, "cy": 360,
                  "distortion": [-0.03, 0.005, 0, 0]}
    return {"seed": seed, "targets": targets,
            "truth": {"enclosure_in_map": mount, "camera_in_enclosure": camera, "intrinsics": intrinsics}}


def truth_pixel(sim: SimTruth, p_map):
    """Where a point appears in the simulated camera (the true camera, not the operator's estimate)."""
    p_enc = sim.enclosure_in_map.inverse().apply(p_map)
    return sim.intrinsics.project(sim.camera_in_enclosure.inverse().apply(p_enc))


def _frame_targets(unit: SensorUnit, sim: SimTruth, t: float, rng: random.Random, clutter: bool = True):
    radar = unit.radar
    targets = []
    for index, spec in enumerate(sim.targets):
        position = target_position(spec, t)
        if position is None:
            continue
        r, az, el = radar_point_from_map(position, unit, sim.enclosure_in_map)
        inside = (r <= radar.max_range_m and radar.azimuth_fov_deg[0] <= az <= radar.azimuth_fov_deg[1]
                  and radar.elevation_fov_deg[0] <= el <= radar.elevation_fov_deg[1])
        if not inside or rng.random() < 0.08:
            continue
        target = {"range_m": r + rng.gauss(0, radar.sigma_range_m), "azimuth_deg": az + rng.gauss(0, radar.sigma_azimuth_deg),
                  "snr_db": 30 - 20 * math.log10(max(r, 1)) + rng.gauss(0, 1.5)}
        if _as_tuple(spec)[2]:
            target["elevation_deg"] = el + rng.gauss(0, radar.sigma_elevation_deg)
        targets.append(target)
    if clutter and rng.random() < 0.02:
        targets.append({"range_m": rng.uniform(2, 12), "azimuth_deg": rng.uniform(-50, 50), "snr_db": rng.uniform(4, 8)})
    return targets


class SimulatorAdapter(RadarAdapter):
    """Live simulated radar. Reports what the HIDDEN TRUE installation would measure; the configured (estimated)
    calibration is what the rest of the system uses, so calibration error shows up as map/overlay error."""

    RATE_HZ = 10.0

    def __init__(self, unit: SensorUnit):
        self.unit, self.sim = unit, unit.simulation
        self.loop_s = max(_as_tuple(t)[1] for t in self.sim.targets) + SIM_LOOP_PADDING_S if self.sim.targets else 10.0
        self._origin = None
        self._step = 0

    def _t(self, step: int) -> float:
        return (step / self.RATE_HZ) % self.loop_s

    def poll(self, now: float) -> list[RadarFrame]:
        if self._origin is None:
            self._origin = now
        out = []
        last = int((now - self._origin) * self.RATE_HZ)
        while self._step <= last and len(out) < 2000:
            rng = random.Random(self.sim.seed * 1_000_003 + self._step)
            stamp = self._origin + self._step / self.RATE_HZ
            measurements = []
            for target in _frame_targets(self.unit, self.sim, self._t(self._step), rng):
                m = RadarMeasurement(stamp, self.unit.radar.sensor_id, self.unit.unit_id, round(target["range_m"], 3),
                                     round(target["azimuth_deg"], 2),
                                     None if "elevation_deg" not in target else round(target["elevation_deg"], 2),
                                     snr_db=round(target["snr_db"], 1))
                if m.valid():
                    measurements.append(m)
            out.append(RadarFrame(stamp, self.unit.radar.sensor_id, tuple(measurements)))
            self._step += 1
        return out

    def truth_positions(self, now: float):
        if self._origin is None:
            return []
        t = self._t(int((now - self._origin) * self.RATE_HZ))
        return [(i, p) for i, spec in enumerate(self.sim.targets) if (p := target_position(spec, t)) is not None]

    def describe(self) -> dict:
        return {"adapter": "simulator", "rate_hz": self.RATE_HZ, "targets": len(self.sim.targets), "loop_s": round(self.loop_s, 1)}


def simulate_reflector(unit_radar, sim: SimTruth, map_point, seed: int, frames: int = 10):
    """Radar capture of a stationary reflector at ``map_point`` as the TRUE installation would see it.
    ``unit_radar`` is a RadarSpec. Returns dict or None if the radar cannot see it."""
    rng = random.Random(seed)
    r, az, el = radar_point_from_map(tuple(map_point), None, sim.enclosure_in_map)
    if not (0.3 <= r <= unit_radar.max_range_m and unit_radar.azimuth_fov_deg[0] <= az <= unit_radar.azimuth_fov_deg[1]
            and unit_radar.elevation_fov_deg[0] <= el <= unit_radar.elevation_fov_deg[1]):
        return None
    samples = []
    for _ in range(frames):
        rr = r + rng.gauss(0, unit_radar.sigma_range_m)
        aa = math.radians(az + rng.gauss(0, unit_radar.sigma_azimuth_deg))
        ee = math.radians(el + rng.gauss(0, unit_radar.sigma_elevation_deg))
        samples.append((rr * math.cos(ee) * math.sin(aa), rr * math.cos(ee) * math.cos(aa), rr * math.sin(ee)))
    mean = [sum(s[i] for s in samples) / frames for i in range(3)]
    spread = math.sqrt(sum(sum((s[i] - mean[i]) ** 2 for i in range(3)) for s in samples) / (3 * max(1, frames - 1)))
    return {"radar": mean, "frames": frames, "range_m": r, "snr_db": round(30 - 20 * math.log10(max(r, 1)), 1),
            "sigma_m": max(0.03, spread / math.sqrt(frames))}
